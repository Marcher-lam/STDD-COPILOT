/**
 * UI scaffolds (frontend item 4): DESIGN.md-driven component/page skeletons.
 */

/** Parse DESIGN.md token table rows into `token: value (role)` strings. */
function extractDesignTokens(designMd) {
  const rows = [];
  for (const line of String(designMd || '').split('\n')) {
    const m = line.match(/^\|\s*`([\w.-]+)`\s*\|\s*`([^`]+)`\s*\|.*?\|\s*([^|]*)\|/);
    if (m && /^#/.test(m[1]) === false) {
      rows.push(m[1] + ': ' + m[2] + ' (' + m[3].trim() + ')');
    }
  }
  return rows;
}

function kebab(input) {
  return String(input || '')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase() || 'component';
}

function pascal(input) {
  return String(input || '')
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map(p => p[0].toUpperCase() + p.slice(1))
    .join('') || 'Component';
}

/**
 * Render a component skeleton for the given framework.
 * @param {string} name  PascalCase component name
 * @param {'react'|'vue'|'html'} framework
 * @param {string[]} tokens  design tokens from DESIGN.md (token: value (role))
 */
function renderComponent(name, framework, tokens = []) {
  const slug = kebab(name);
  const tokenLines = tokens.length > 0
    ? tokens.map(t => '//   ' + t).join('\n')
    : '//   (no DESIGN.md tokens found — use semantic vars like var(--color-primary))';
  const header = [
    '// Generated by `stdd ui generate`. Design tokens (from DESIGN.md):',
    tokenLines,
    '// Extend the same token source; never hardcode new values.',
  ].join('\n');

  if (framework === 'vue') {
    return [
      header,
      '<template>',
      "  <section class=\"" + slug + "\" :aria-label=\"'" + slug + "'\">",
      '    <!-- TODO: implement ' + name + ' -->',
      '  </section>',
      '</template>',
      '',
      '<script setup lang="ts">',
      'defineProps<Record<string, unknown>>();',
      '</script>',
      '',
      '<style scoped>',
      '.' + slug + ' {',
      '  /* tokens from DESIGN.md */',
      '}',
      '</style>',
      ''
    ].join('\n');
  }

  if (framework === 'html') {
    return [
      '<!-- ' + header.replace(/\n/g, '\n     ') + ' -->',
      '<section class="' + slug + '" role="region" aria-label="' + slug + '">',
      '  <!-- TODO: implement ' + name + ' -->',
      '</section>',
      ''
    ].join('\n');
  }

  // react (default)
  return [
    header,
    '',
    "export function " + name + "() {",
    "  return (",
    "    <section className=\"" + slug + "\" role='region' aria-label='" + slug + "'>",
    "      {/* TODO: implement " + name + " */}",
    "    </section>",
    "  );",
    "}",
    ""
  ].join('\n');
}

module.exports = { renderComponent, extractDesignTokens, kebab, pascal };
