const fs = require('fs');
const path = require('path');
const { resolveChangeDir } = require('../../utils/change-utils');
const { walkFiles } = require('../../utils/file-walker');
const { parseBddScenarios } = require('../../utils/bdd-scenario-parser');

class PipelineCommand {
  constructor(cwd = process.cwd()) { this.cwd = cwd; }

  execute(changeName, options = {}) {
    const changeDir = changeName ? resolveChangeDir(path.join(this.cwd, 'stdd'), changeName) : null;
    const specsDir = changeName ? path.join(changeDir || '', 'specs') : path.join(this.cwd, 'stdd', 'specs');
    if (!fs.existsSync(specsDir)) throw new Error(`Spec directory not found: ${path.relative(this.cwd, specsDir)}`);
    const ir = this.parseSpecs(walkFiles(specsDir, { extensions: ['.feature', '.md'], skipDirs: new Set() }), this.cwd);

    // test_pipeline config (stdd/config.yaml) is honored: output_dir for the
    // test skeleton, ir_dir for the IR, placeholder_mode for pending bodies.
    const cfg = this._loadTestPipelineConfig();
    const outDir = changeName ? path.join(changeDir, 'pipeline') : path.join(this.cwd, 'stdd', 'pipeline');
    const testDir = cfg.output_dir ? path.join(this.cwd, cfg.output_dir) : outDir;
    const irDir = cfg.ir_dir ? path.join(this.cwd, cfg.ir_dir) : outDir;
    fs.mkdirSync(testDir, { recursive: true });
    fs.mkdirSync(irDir, { recursive: true });
    const irPath = path.join(irDir, 'ir.json');
    const testPath = path.join(testDir, 'generated-tests.test.js');
    fs.writeFileSync(irPath, JSON.stringify(ir, null, 2), 'utf8');
    fs.writeFileSync(testPath, this.generateTestSkeleton(ir, cfg.placeholder_mode), 'utf8');
    if (options.json) console.log(JSON.stringify({ status: 'generated', ir: irPath, tests: testPath }, null, 2));
    else console.log(`Generated pipeline IR and test skeleton in ${path.relative(this.cwd, outDir)}`);
    return { status: 'generated', ir: irPath, tests: testPath, files: [irPath, testPath] };
  }

  _loadTestPipelineConfig() {
    try {
      const yaml = require('js-yaml');
      const configPath = path.join(this.cwd, 'stdd', 'config.yaml');
      if (!fs.existsSync(configPath)) return {};
      const config = yaml.load(fs.readFileSync(configPath, 'utf8')) || {};
      return config.test_pipeline || {};
    } catch {
      return {};
    }
  }

  parseSpecs(files, cwd) {
    const scenarios = parseBddScenarios(files, cwd);
    return { version: '1.0', generatedAt: new Date().toISOString(), scenarios };
  }

  generateTestSkeleton(ir, placeholderMode = 'todo') {
    const lines = ['// Auto-generated by stdd pipeline', "const assert = require('assert');", ''];
    for (const scenario of ir.scenarios) {
      const name = JSON.stringify(scenario.name);
      if (placeholderMode === 'skip') {
        lines.push(`test.skip(${name}, () => {});`, '');
        continue;
      }
      const body = placeholderMode === 'pending'
        ? `  assert.ok(false, 'Pending acceptance test');`
        : `  assert.ok(false, 'Implement acceptance test from generated IR');`;
      lines.push(`test(${name}, () => {`);
      if (placeholderMode === 'todo') lines.push(`  // TODO: implement from the scenario below`);
      lines.push(`  // Source: ${scenario.source}`);
      for (const step of scenario.steps) lines.push(`  // ${step}`);
      lines.push(body);
      lines.push('});', '');
    }
    return lines.join('\n');
  }
}

module.exports = { PipelineCommand };
